// ======================================================
// NOMBRE DEL SISTEMA
// ======================================================
const SISTEMA =
    "SIGI-POA DGEMS";



// ======================================================
// ENCABEZADO SECUNDARIO
// ======================================================

function dibujarEncabezadoSecundario(
    doc,
    reporte
) {

    // ==============================================
    // FUENTE
    // ==============================================

    doc.setFont(

        "helvetica",

        "normal"

    );

    doc.setFontSize(10);


    // ==============================================
    // COLOR TEXTO
    // ==============================================

    doc.setTextColor(

        78,

        77,

        77

    );


    // ==============================================
    // TEXTO
    // ==============================================

    doc.text(

        `${SISTEMA} | Reporte de ${reporte.identidadReporte.tipo}`,

        15,

        12

    );


    // ==============================================
    // LÍNEA DIVISORIA
    // ==============================================

    doc.setDrawColor(

        180,

        180,

        180

    );


    doc.line(

        15,

        16,

        195,

        16

    );

}


// ======================================================
// EXPORTAR FUNCIÓN
// ======================================================

module.exports =
    dibujarEncabezadoSecundario;